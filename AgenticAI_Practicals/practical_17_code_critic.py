from langchain_ollama import OllamaLLM


llm = OllamaLLM(
    model="llama3.2",
    temperature=0.2
)

task=input("Programming requirement")


code = llm.invoke(
    f""" 
    Write only code for the following {task}
    """
)

print("code generated by LLM ")
print(code)


review = llm.invoke(
    f"""
    Act as a code reviewer for this {code}
    Identify :
    1. Bugs
    2. Improvements
    3. Best practices not followed
    
    """
)

print("Review : ")
print(review)